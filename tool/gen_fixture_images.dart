// Embeds test/fixtures/images/* into integration_test/fixture_images.g.dart so the on-device
// integration test can read them without bundling them into the app as assets.
//
// Usage: dart run tool/gen_fixture_images.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final dir = Directory('test/fixtures/images');
  final files = dir.existsSync()
      ? (dir.listSync().whereType<File>().where((f) => RegExp(r'\.(jpe?g|png)$', caseSensitive: false).hasMatch(f.path)).toList()
        ..sort((a, b) => a.path.compareTo(b.path)))
      : <File>[];

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_fixture_images.dart. Do not edit or commit.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('/// File stem → base64-encoded image bytes.')
    ..writeln('const Map<String, String> fixtureImages = {');
  for (final f in files) {
    final name = f.uri.pathSegments.last;
    final stem = name.substring(0, name.lastIndexOf('.'));
    out.writeln("  '$stem': '${base64Encode(f.readAsBytesSync())}',");
  }
  out.writeln('};');

  File('integration_test/fixture_images.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('Embedded ${files.length} fixture image(s).');
}
